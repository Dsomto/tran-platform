const STAGE = "STAGE_8";
const SOURCE_RELEASE = "stage8-results-2026-09-01-corrected-links";
const FINAL_RELEASE = "stage8-results-2026-09-01-final-signed-links";
const ORIGIN = "https://ubuntubridgeinitiatives.org";
const EXPECTED_RECIPIENTS = 65;
const CONFIRMATION = "QUEUE_FINAL_STAGE8_LINK_REPAIR";

type LinkSet = {
  certificate: string;
  verify: string;
  achievement: string;
  close: string;
  reference: string;
  performance: string;
  dossier: string;
  certificateId: string;
};

function contextString(value: unknown, key: string): string | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const field = (value as Record<string, unknown>)[key];
  return typeof field === "string" ? field : null;
}

function releaseId(value: unknown): string | null {
  return contextString(value, "releaseId");
}

function linksFor(reportId: string, internId: string): LinkSet {
  return {
    certificate: certificateUrl({ origin: ORIGIN, reportId, internId }),
    verify: verifyUrl({ origin: ORIGIN, reportId, internId }),
    achievement: passLetterUrl({ origin: ORIGIN, reportId, internId }),
    close: letterUrl({ origin: ORIGIN, reportId, internId }),
    reference: referenceUrl({ origin: ORIGIN, reportId, internId }),
    performance: performanceRecordUrl({ origin: ORIGIN, reportId, internId }),
    dossier: dossierUrl({ origin: ORIGIN, reportId, internId }),
    certificateId: certificateIdFor(reportId),
  };
}

function replaceUrl(body: string, path: string, reportId: string, replacement: string): string {
  const escapedPath = path.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const escapedReport = reportId.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const normal = new RegExp(
    `https:\\/\\/ubuntubridgeinitiatives\\.org\\/${escapedPath}\\/${escapedReport}\\?sig=[a-f0-9]{16}`,
    "gi"
  );
  const encoded = new RegExp(
    `https%3A%2F%2Fubuntubridgeinitiatives\\.org%2F${encodeURIComponent(path)}%2F${escapedReport}%3Fsig%3D[a-f0-9]{16}`,
    "gi"
  );
  return body.replace(normal, replacement).replace(encoded, encodeURIComponent(replacement));
}

function finalNotice(): string {
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="border-collapse:separate;margin:0 0 18px;background:#ECFDF5;border:1px solid #6EE7B7;border-radius:8px;overflow:hidden;"><tr><td style="padding:16px 18px;"><div style="font-size:12px;font-weight:900;letter-spacing:.08em;text-transform:uppercase;color:#047857;margin:0 0 5px;">Final verified links</div><p style="font-size:14px;line-height:1.65;color:#064E3B;margin:0;">Please use the document buttons in this email. The previous correction reached the live website but carried invalid link signatures. These links were regenerated by the live application. Your score, progression decision and documents have not changed.</p></td></tr></table>`;
}

function repairBody(source: string, reportId: string, links: LinkSet): string {
  let body = source;
  body = replaceUrl(body, "api/certificate", reportId, links.certificate);
  body = replaceUrl(body, "verify", reportId, links.verify);
  body = replaceUrl(body, "api/pass-letter", reportId, links.achievement);
  body = replaceUrl(body, "api/letter", reportId, links.close);
  body = replaceUrl(body, "api/reference-letter", reportId, links.reference);
  body = replaceUrl(body, "api/performance-record", reportId, links.performance);
  body = replaceUrl(body, "api/portfolio-dossier", reportId, links.dossier);
  body = body.replace(/((?:&amp;|&)certId=)[A-F0-9]{12}/gi, `$1${links.certificateId}`);

  const expectedSignatures = new Set(
    [
      links.certificate,
      links.verify,
      links.achievement,
      links.close,
      links.reference,
      links.performance,
      links.dossier,
    ].map((url) => new URL(url).searchParams.get("sig"))
  );
  const signatures = [...body.matchAll(/sig(?:=|%3D)([a-f0-9]{16})/gi)].map((match) => match[1]);
  if (signatures.length === 0 || signatures.some((sig) => !expectedSignatures.has(sig))) {
    throw new Error(`Signature replacement failed for report ${reportId}`);
  }
  const certIds = [...body.matchAll(/(?:&amp;|&)certId=([A-F0-9]{12})/gi)].map((match) => match[1]);
  if (certIds.some((id) => id !== links.certificateId)) {
    throw new Error(`Credential ID replacement failed for report ${reportId}`);
  }
  if (/localhost|127\.0\.0\.1/i.test(body)) {
    throw new Error(`Local address remains in report ${reportId}`);
  }

  const notice = finalNotice();
  return /<body[^>]*>/i.test(body)
    ? body.replace(/(<body[^>]*>)/i, `$1${notice}`)
    : `${notice}${body}`;
}

async function releaseRows() {
  const rows = await prisma.emailQueueItem.findMany({
    where: { status: { in: ["PENDING", "SENT", "FAILED"] } },
    orderBy: { enqueuedAt: "asc" },
  });
  return {
    source: rows.filter((row) => releaseId(row.context) === SOURCE_RELEASE),
    existing: rows.filter((row) => releaseId(row.context) === FINAL_RELEASE),
  };
}

async function buildRepair() {
  const { source, existing } = await releaseRows();
  if (source.length !== EXPECTED_RECIPIENTS) {
    throw new Error(`Expected ${EXPECTED_RECIPIENTS} source messages; found ${source.length}`);
  }
  if (source.some((row) => row.status !== "SENT")) {
    throw new Error("Every source correction must be SENT before repair");
  }
  if (existing.length > 0) {
    throw new Error(`Final repair already exists with ${existing.length} message(s)`);
  }

  const reportIds = source.map((row) => contextString(row.context, "reportId"));
  if (reportIds.some((id) => !id)) throw new Error("A source message is missing reportId");
  const reports = await prisma.stageReport.findMany({
    where: { id: { in: reportIds as string[] }, stage: STAGE },
    include: { intern: { include: { user: true } } },
  });
  const byId = new Map(reports.map((report) => [report.id, report]));
  if (byId.size !== EXPECTED_RECIPIENTS) {
    throw new Error(`Expected ${EXPECTED_RECIPIENTS} Stage 8 reports; found ${byId.size}`);
  }

  const repaired = source.map((row) => {
    const reportId = contextString(row.context, "reportId");
    const report = reportId ? byId.get(reportId) : null;
    if (!report || report.intern.user.id !== row.userId) {
      throw new Error(`Recipient/report binding failed for queue item ${row.id}`);
    }
    const links = linksFor(report.id, report.intern.id);
    return {
      userId: row.userId,
      toEmail: row.toEmail,
      kind: row.kind,
      subject: `Final link correction: ${row.subject.replace(/^Correction:\s*/i, "")}`,
      body: repairBody(row.body, report.id, links),
      context: {
        ...(row.context && typeof row.context === "object" && !Array.isArray(row.context)
          ? row.context
          : {}),
        releaseId: FINAL_RELEASE,
        repairedFromReleaseId: SOURCE_RELEASE,
        repairedFromQueueItemId: row.id,
        correction: "production-signed-document-links",
      },
      testUrls: report.status === "PASSED"
        ? [
            { label: "pass-certificate", url: links.certificate, contentType: "application/pdf" },
            { label: "pass-verification", url: links.verify, contentType: "text/html" },
            { label: "pass-achievement", url: links.achievement, contentType: "application/pdf" },
            { label: "pass-reference", url: links.reference, contentType: "application/pdf" },
            { label: "pass-performance", url: links.performance, contentType: "application/pdf" },
            { label: "pass-dossier", url: links.dossier, contentType: "application/pdf" },
          ]
        : [
            { label: "departure-close", url: links.close, contentType: "application/pdf" },
            { label: "departure-reference", url: links.reference, contentType: "application/pdf" },
            { label: "departure-performance", url: links.performance, contentType: "application/pdf" },
            { label: "departure-dossier", url: links.dossier, contentType: "application/pdf" },
          ],
    };
  });

  if (new Set(repaired.map((row) => row.toEmail.toLowerCase())).size !== EXPECTED_RECIPIENTS) {
    throw new Error("Repair recipients are not unique");
  }
  return repaired;
}

export async function GET() {
  const auth = await requireApiSuperAdmin();
  if (auth.response) return auth.response;
  try {
    const repaired = await buildRepair();
    const passer = repaired.find((row) => row.testUrls.length === 6);
    const departure = repaired.find((row) => row.testUrls.length === 4);
    const testUrls = [...(passer?.testUrls ?? []), ...(departure?.testUrls ?? [])];
    const checks = await Promise.all(
      testUrls.map(async (test) => {
        try {
          const response = await fetch(test.url, {
            cache: "no-store",
            redirect: "manual",
            signal: AbortSignal.timeout(45_000),
          });
          const contentType = response.headers.get("content-type") ?? "";
          return {
            label: test.label,
            status: response.status,
            contentType,
            valid: response.status === 200 && contentType.startsWith(test.contentType),
          };
        } catch {
          return { label: test.label, status: 0, contentType: "", valid: false };
        }
      })
    );
    return Response.json({
      ready: checks.length === 10 && checks.every((check) => check.valid),
      recipients: repaired.length,
      checks,
    });
  } catch (error) {
    return Response.json(
      { error: error instanceof Error ? error.message : "Stage 8 link repair failed" },
      { status: 409 }
    );
  }
}

export async function POST(request: NextRequest) {
  const auth = await requireApiSuperAdmin();
  if (auth.response) return auth.response;
  try {
    const body = await request.json();
    if (body?.confirmation !== CONFIRMATION) {
      return Response.json({ error: "Explicit repair confirmation is required" }, { status: 400 });
    }
    const repaired = await buildRepair();
    await prisma.emailQueueItem.createMany({
      data: repaired.map((row) => ({
        userId: row.userId,
        toEmail: row.toEmail,
        kind: row.kind,
        subject: row.subject,
        body: row.body,
        context: row.context,
      })),
    });
    await recordAudit({
      actor: auth.session,
      action: "STAGE8_RESULT_LINKS_REPAIRED",
      targetType: "STAGE_RESULTS",
      targetId: STAGE,
      details: {
        sourceRelease: SOURCE_RELEASE,
        finalRelease: FINAL_RELEASE,
        recipients: repaired.length,
        changed: "document URLs and credential IDs only",
      },
      ...auditMetaFromRequest(request),
    });
    return Response.json({ queued: repaired.length, releaseId: FINAL_RELEASE });
  } catch (error) {
    return Response.json(
      { error: error instanceof Error ? error.message : "Stage 8 link repair failed" },
      { status: 409 }
    );
  }
}
